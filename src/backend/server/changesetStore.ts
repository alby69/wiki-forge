import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { atomicWriteFile, softDelete } from './safeFs';

/**
 * A7 — Plan / Review / Apply for LLM-authored edits.
 *
 * A changeset is a durable proposal: it records the original bytes, the
 * proposed bytes, a rationale and its sources. Nothing touches the wiki until
 * a human calls `apply`. All filesystem writes go through the shared safeFs
 * layer (atomic writes + soft deletes), so there is ONE durability policy.
 *
 * This is the live counterpart of the old, orphaned `wikiforge/vault.py`.
 */

export type ChangesetAction = 'create' | 'modify' | 'delete';
export type ChangesetStatus = 'pending' | 'applied' | 'rejected';

export interface ChangesetEdit {
  file: string;
  action: ChangesetAction;
  original_content?: string;
  proposed_content?: string;
  find?: string;
  replace?: string;
  /** A3 — refuse to apply when the note changed after staging. */
  requireOriginal?: boolean;
  /** A3 — snapshot written by the store just before this edit was applied. */
  snapshotId?: string;
}

/** A3 — advisory context copied verbatim from a `wikiforge.finding/v1` item. */
export interface ChangesetFinding {
  findingId: string;
  kind: string;
  confidence: number;
  evidence: string[];
  targetPath: string;
  proposedAction: string;
}

export interface Changeset {
  id: string;
  timestamp: string;
  author: string;
  status: ChangesetStatus;
  description: string;
  rationale?: string;
  sources?: string[];
  edits: ChangesetEdit[];
  applied_at?: string;
  rejected_reason?: string;
  /** B5 — additive, server-trusted provenance (absent in legacy mode). */
  actor?: string;
  applied_by?: string;
  rejected_by?: string;
  /** A3 — present only on changesets staged from a Finding. */
  finding?: ChangesetFinding;
  /** A3 — set by `rollback()` after restoring the original bytes. */
  rolled_back_at?: string;
  rolled_back_by?: string;
}

export interface StageChangesetInput {
  description: string;
  edits: ChangesetEdit[];
  author?: string;
  rationale?: string;
  sources?: string[];
  /** B5 — set by the strict-mode HTTP adapter, never from the raw body. */
  actor?: string;
  /** A3 — advisory context; never drives a write by itself. */
  finding?: ChangesetFinding;
}

export interface ChangesetStoreOptions {
  /** A3 — called before each wiki write; the returned id is kept for audit/UI. */
  snapshot?: (file: string, content: string, reason: string) => Promise<string | undefined>;
}

export class ChangesetStore {
  private readonly dir: string;

  constructor(
    private readonly projectRoot: string,
    private readonly options: ChangesetStoreOptions = {},
  ) {
    this.dir = path.join(projectRoot, '.wiki-forge', 'changesets');
  }

  private file(id: string): string {
    // ids are generated by us; reject anything that could escape the store.
    if (!/^cs-[0-9a-z-]+$/.test(id)) throw new Error(`Invalid changeset id '${id}'`);
    return path.join(this.dir, `${id}.json`);
  }

  /** Resolve a wiki-relative path and guarantee it stays inside the project. */
  private resolveWikiPath(relative: string): string {
    const clean = relative.replace(/\\/g, '/').replace(/^\/+/, '');
    if (!clean || clean.split('/').includes('..')) {
      throw new Error(`Unsafe changeset file path '${relative}'`);
    }
    const absolute = path.resolve(this.projectRoot, clean);
    const inside = path.relative(this.projectRoot, absolute);
    if (inside.startsWith('..') || path.isAbsolute(inside)) {
      throw new Error(`Changeset path escapes the project: '${relative}'`);
    }
    return absolute;
  }

  private async read(id: string): Promise<Changeset | undefined> {
    try {
      return JSON.parse(await fs.readFile(this.file(id), 'utf-8')) as Changeset;
    } catch {
      return undefined;
    }
  }

  private async write(changeset: Changeset): Promise<void> {
    await atomicWriteFile(this.file(changeset.id), JSON.stringify(changeset, null, 2), 'utf-8');
  }

  async stage(input: StageChangesetInput): Promise<Changeset> {
    if (!input.description?.trim()) throw new Error('A changeset needs a description');
    if (!Array.isArray(input.edits) || input.edits.length === 0) {
      throw new Error('A changeset needs at least one edit');
    }

    const processed: ChangesetEdit[] = [];
    for (const edit of input.edits) {
      const absolute = this.resolveWikiPath(edit.file);
      const original = await fs.readFile(absolute, 'utf-8').catch(() => '');
      processed.push({
        ...edit,
        file: path.relative(this.projectRoot, absolute).replace(/\\/g, '/'),
        original_content: original,
      });
    }

    const changeset: Changeset = {
      id: `cs-${Date.now()}-${Math.random().toString(16).slice(2, 8)}`,
      timestamp: new Date().toISOString(),
      author: input.author || 'agent',
      status: 'pending',
      description: input.description.trim(),
      rationale: input.rationale,
      sources: input.sources,
      edits: processed,
      ...(input.actor ? { actor: input.actor } : {}),
      ...(input.finding ? { finding: input.finding } : {}),
    };
    await this.write(changeset);
    return changeset;
  }

  async list(status?: ChangesetStatus): Promise<Changeset[]> {
    let files: string[];
    try {
      files = (await fs.readdir(this.dir)).filter((name) => /^cs-.*\.json$/.test(name));
    } catch {
      return [];
    }
    const all = await Promise.all(files.map(async (name) => {
      try {
        return JSON.parse(await fs.readFile(path.join(this.dir, name), 'utf-8')) as Changeset;
      } catch {
        return undefined;
      }
    }));
    return all
      .filter((item): item is Changeset => Boolean(item))
      .filter((item) => !status || item.status === status)
      .sort((a, b) => b.timestamp.localeCompare(a.timestamp));
  }

  async get(id: string): Promise<Changeset> {
    const changeset = await this.read(id);
    if (!changeset) throw new Error(`Changeset '${id}' not found`);
    return changeset;
  }

  /** Apply every edit after human review. Never called by the LLM itself. */
  async apply(id: string, actor?: string): Promise<{ changesetId: string; appliedFiles: string[] }> {
    const changeset = await this.get(id);
    if (changeset.status !== 'pending') {
      throw new Error(`Changeset '${id}' is '${changeset.status}', cannot re-apply`);
    }

    const appliedFiles: string[] = [];
    for (const edit of changeset.edits) {
      const absolute = this.resolveWikiPath(edit.file);
      const current = await fs.readFile(absolute, 'utf-8').catch(() => '');

      // A3 — a Finding proposal is bound to the bytes it was staged against.
      if (edit.requireOriginal && current !== edit.original_content) {
        throw new Error(`Changeset '${changeset.id}' is stale: ${edit.file} changed after staging`);
      }

      // A3 — pre-write snapshot for the Review Studio diff/restore flow. The
      // hook is best-effort and lives in AgentServer, so this store stays
      // usable in unit tests without any server wiring.
      const snapshotId = await this.options.snapshot?.(
        edit.file,
        current,
        `changeset ${changeset.id} (${changeset.finding?.findingId ?? 'apply'})`,
      );
      if (snapshotId) edit.snapshotId = snapshotId;

      if (edit.action === 'delete') {
        try {
          await softDelete(absolute, this.projectRoot);
          appliedFiles.push(edit.file);
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
        }
        continue;
      }

      let content = edit.proposed_content ?? '';
      if (edit.find !== undefined && edit.replace !== undefined) {
        if (!current.includes(edit.find)) {
          throw new Error(`Find block not found in ${edit.file}`);
        }
        content = current.replace(edit.find, edit.replace);
      }
      await atomicWriteFile(absolute, content, 'utf-8');
      appliedFiles.push(edit.file);
    }

    changeset.status = 'applied';
    changeset.applied_at = new Date().toISOString();
    if (actor) {
      changeset.actor = actor;
      changeset.applied_by = actor;
    }
    await this.write(changeset);
    return { changesetId: changeset.id, appliedFiles };
  }

  async reject(id: string, reason = '', actor?: string): Promise<Changeset> {
    const changeset = await this.get(id);
    if (changeset.status !== 'pending') {
      throw new Error(`Changeset '${id}' is '${changeset.status}', cannot reject`);
    }
    changeset.status = 'rejected';
    changeset.rejected_reason = reason;
    if (actor) {
      changeset.actor = actor;
      changeset.rejected_by = actor;
    }
    await this.write(changeset);
    return changeset;
  }

  /**
   * A3 — restore the bytes captured at staging time.
   *
   * It reuses the changeset's own `original_content`, so it also covers a
   * created proposal note (original = absence) without inventing a new endpoint:
   * the UI keeps using the existing changeset/review routes, while this method
   * is the backend primitive used by the A3 acceptance tests.
   */
  async rollback(id: string, actor?: string): Promise<Changeset> {
    const changeset = await this.get(id);
    if (changeset.status === 'pending') {
      throw new Error(`Changeset '${id}' is pending, nothing to roll back`);
    }

    for (const edit of changeset.edits) {
      const absolute = this.resolveWikiPath(edit.file);
      const original = edit.original_content ?? '';
      if (original) {
        await atomicWriteFile(absolute, original, 'utf-8');
      } else {
        // A created file rolls back to its original state: absent. Keep it
        // recoverable in the shared trash instead of unlinking it.
        try {
          await softDelete(absolute, this.projectRoot);
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
        }
      }
    }

    changeset.status = 'rejected';
    changeset.rejected_reason = 'rollback A3';
    changeset.rolled_back_at = new Date().toISOString();
    if (actor) {
      changeset.actor = actor;
      changeset.rolled_back_by = actor;
    }
    await this.write(changeset);
    return changeset;
  }
}
