#!/usr/bin/env python3
"""
scripts/check_docs_sync.py
Automated documentation and Agent Skills consistency checker for wiki-forge.

Checks:
1. Parses `skills/*/SKILL.md` frontmatter `triggers.commands` lists to build canonical command set.
2. Verifies that every trigger command is mentioned in `docs/riferimenti/SLASH_COMMANDS_REFERENCE.md`,
   the single human-readable catalog. `README.md` and `TUTORIAL.md` are pointers, not copies.
3. Verifies semantic references: `docs/help/*.md` markers must carry the sha256 of the
   `DOC_BLOCK` they point to. Use `--fix` to refresh those markers after editing a master block.
4. Verifies version parity between `package.json` ("version") and top-most version in `docs/riferimenti/CHANGELOG.md`.
5. Validates `docs/help/*.md` in-app guide topics: mandatory frontmatter, `id == filename`,
   slugged id, numeric order, non-empty body, and coverage in `docs/README.md`.
6. Verifies that the committed OKF bundle in `projects/wikiforge/wiki/` matches a fresh
   projection of `docs/` generated by `scripts/docs_to_wiki.py` (no drift).
7. Verifies that active docs describe the unified `.wiki-forge/` state root.
8. Rejects absolute "no cloud" claims and requires the inert backup hook to be
   documented as inactive.
9. Verifies that README.md, ARCHITECTURE.md and the other active docs quote the
   counts generated by scripts/gen_doc_metrics.py from the command manifest.
"""

import os
import re
import sys
import json
import hashlib
from pathlib import Path

def parse_skill_commands(repo_root: Path) -> set[str]:
    skills_dir = repo_root / "skills"
    commands = set()
    if not skills_dir.exists():
        print("ERROR: skills/ directory does not exist.", file=sys.stderr)
        return commands

    for skill_file in skills_dir.glob("*/SKILL.md"):
        content = skill_file.read_text(encoding="utf-8")
        # Match YAML frontmatter between --- and ---
        fm_match = re.search(r"^---\s*\n(.*?)\n---", content, re.DOTALL)
        if not fm_match:
            continue
        frontmatter = fm_match.group(1)
        # Find triggers: commands: [...] or list items
        cmd_match = re.search(r"commands:\s*\[(.*?)\]", frontmatter)
        if cmd_match:
            cmds = [c.strip().strip("'\"") for c in cmd_match.group(1).split(",")]
            for cmd in cmds:
                if cmd:
                    # Strip leading slash if present for normalized matching
                    norm_cmd = cmd.lstrip("/")
                    commands.add(norm_cmd)
        else:
            # Check multiline list format under commands:
            lines = frontmatter.splitlines()
            in_commands = False
            for line in lines:
                if re.match(r"^\s*commands:\s*$", line):
                    in_commands = True
                    continue
                if in_commands:
                    if re.match(r"^\s*-\s*", line):
                        cmd = re.sub(r"^\s*-\s*", "", line).strip().strip("'\"")
                        if cmd:
                            commands.add(cmd.lstrip("/"))
                    elif not re.match(r"^\s+", line):
                        in_commands = False
    return commands

def check_doc_mentions(commands: set[str], doc_path: Path, doc_name: str) -> list[str]:
    errors = []
    if not doc_path.exists():
        errors.append(f"Document {doc_name} ({doc_path}) not found.")
        return errors

    content = doc_path.read_text(encoding="utf-8")
    for cmd in sorted(commands):
        # Search for command as exact word, or slash command, or quoted
        pattern = re.compile(rf"(\b{re.escape(cmd)}\b|/{re.escape(cmd)})", re.IGNORECASE)
        if not pattern.search(content):
            errors.append(f"Command '{cmd}' is defined in skills/ but missing from {doc_name}")
    return errors

def check_version_sync(repo_root: Path) -> list[str]:
    errors = []
    pkg_path = repo_root / "package.json"
    changelog_path = repo_root / "docs" / "riferimenti" / "CHANGELOG.md"

    if not pkg_path.exists():
        errors.append("package.json missing")
        return errors
    if not changelog_path.exists():
        errors.append("docs/riferimenti/CHANGELOG.md missing")
        return errors

    try:
        pkg_data = json.loads(pkg_path.read_text(encoding="utf-8"))
        pkg_version = pkg_data.get("version")
    except Exception as e:
        errors.append(f"Failed to parse package.json: {e}")
        return errors

    changelog_content = changelog_path.read_text(encoding="utf-8")
    cl_match = re.search(r"##\s*\[([0-9]+\.[0-9]+\.[0-9]+)\]", changelog_content)
    if not cl_match:
        errors.append("Could not find top version header in CHANGELOG.md")
        return errors

    cl_version = cl_match.group(1)
    if pkg_version != cl_version:
        errors.append(
            f"Version mismatch: package.json is '{pkg_version}' but top CHANGELOG.md entry is '{cl_version}'"
        )

    return errors

HELP_REQUIRED_KEYS = ("id", "title", "icon", "order", "group", "mode", "keywords", "context")

# Master blocks mirrored by hash in docs/help/. Add a block here when another
# help topic needs to stay semantically in sync with a canonical section.
DOC_BLOCKS = {
    "slash-commands": "docs/riferimenti/SLASH_COMMANDS_REFERENCE.md",
    "script-automation": "docs/riferimenti/SCRIPT_AUTOMATION_REFERENCE.md",
}
DOC_BLOCK_REF_RE = re.compile(
    r"<!--\s*DOC_BLOCK_REF:([a-z0-9-]+)\s+(\S+)\s+sha256:([0-9a-f]{64})\s*-->",
    re.IGNORECASE,
)

def normalise_block(block: str) -> str:
    """Stable representation used for the semantic hash (trailing spaces ignored)."""
    return "\n".join(line.rstrip() for line in block.strip().splitlines())

def check_semantic_refs(repo_root: Path, fix: bool = False) -> list[str]:
    """Verify that docs/help references point to the current master block hash."""
    errors: list[str] = []
    hashes: dict[str, str] = {}

    for name, master_rel in DOC_BLOCKS.items():
        master = repo_root / master_rel
        if not master.exists():
            errors.append(f"Semantic block master '{master_rel}' does not exist.")
            continue
        content = master.read_text(encoding="utf-8")
        pattern = re.compile(
            r"<!--\s*DOC_BLOCK:" + re.escape(name) + r"\s*-->(.*?)"
            r"<!--\s*/DOC_BLOCK:" + re.escape(name) + r"\s*-->",
            re.DOTALL,
        )
        match = pattern.search(content)
        if not match:
            errors.append(f"'{master_rel}' has no DOC_BLOCK:{name} section.")
            continue
        digest = hashlib.sha256(normalise_block(match.group(1)).encode("utf-8")).hexdigest()
        hashes[name] = digest

    help_dir = repo_root / "docs" / "help"
    seen: set[str] = set()
    for topic in sorted(help_dir.glob("*.md")):
        original = topic.read_text(encoding="utf-8")
        updated = original
        for ref in reversed(list(DOC_BLOCK_REF_RE.finditer(original))):
            name, source, digest = ref.group(1), ref.group(2), ref.group(3).lower()
            seen.add(name)
            if name not in DOC_BLOCKS:
                errors.append(f"docs/help/{topic.name}: unknown semantic block '{name}'.")
                continue
            if source != DOC_BLOCKS[name]:
                errors.append(
                    f"docs/help/{topic.name}: block '{name}' must reference "
                    f"'{DOC_BLOCKS[name]}', got '{source}'."
                )
                continue
            if name not in hashes:
                continue
            expected = hashes[name]
            if digest != expected:
                if fix:
                    replacement = f"<!-- DOC_BLOCK_REF:{name} {source} sha256:{expected} -->"
                    updated = updated[:ref.start()] + replacement + updated[ref.end():]
                else:
                    errors.append(
                        f"docs/help/{topic.name}: stale hash for '{name}' "
                        f"(expected {expected[:12]}…, got {digest[:12]}…); "
                        "run 'python scripts/check_docs_sync.py --fix'."
                    )
        if fix and updated != original:
            topic.write_text(updated, encoding="utf-8")

    for name in DOC_BLOCKS:
        if name not in seen:
            errors.append(f"docs/help/: no DOC_BLOCK_REF marker found for '{name}'.")
    return errors

def check_help_topics(repo_root: Path) -> list[str]:
    errors = []
    help_dir = repo_root / "docs" / "help"
    if not help_dir.exists():
        errors.append("docs/help/ directory does not exist.")
        return errors

    topic_files = sorted(help_dir.glob("*.md"))
    if not topic_files:
        errors.append("docs/help/ contains no .md topics.")
        return errors

    docs_index = repo_root / "docs" / "README.md"
    index_content = docs_index.read_text(encoding="utf-8") if docs_index.exists() else ""

    ids = []
    for topic_file in topic_files:
        content = topic_file.read_text(encoding="utf-8")
        fm_match = re.search(r"^---\s*\n(.*?)\n---\s*\n", content, re.DOTALL)
        if not fm_match:
            errors.append(f"docs/help/{topic_file.name}: missing YAML frontmatter.")
            continue
        frontmatter = fm_match.group(1)
        body = content[fm_match.end():]

        fm_keys = dict(
            (m.group(1), m.group(2).strip())
            for m in re.finditer(r"^([a-z_]+):\s*(.*)$", frontmatter, re.MULTILINE)
        )
        for key in HELP_REQUIRED_KEYS:
            if key not in fm_keys or not fm_keys[key]:
                errors.append(f"docs/help/{topic_file.name}: missing frontmatter key '{key}'.")

        topic_id = fm_keys.get("id", "")
        if topic_id:
            ids.append(topic_id)
            if topic_id != topic_file.stem:
                errors.append(
                    f"docs/help/{topic_file.name}: id '{topic_id}' does not match filename stem '{topic_file.stem}'."
                )
            if not re.fullmatch(r"[a-z0-9-]+", topic_id):
                errors.append(f"docs/help/{topic_file.name}: id '{topic_id}' must match ^[a-z0-9-]+$.")

        order = fm_keys.get("order", "")
        if order and not re.fullmatch(r"\d+", order):
            errors.append(f"docs/help/{topic_file.name}: order '{order}' must be an integer.")

        if not body.strip():
            errors.append(f"docs/help/{topic_file.name}: body is empty.")

        if index_content and topic_id and topic_id not in index_content:
            errors.append(f"docs/help/{topic_file.name}: topic id '{topic_id}' not listed in docs/README.md.")

    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    for dup in duplicates:
        errors.append(f"docs/help: duplicate topic id '{dup}'.")

    return errors

def check_generated_wiki(repo_root: Path) -> list[str]:
    """Ensure the committed self-documentation wiki is in sync with docs/."""
    try:
        import docs_to_wiki
    except Exception as exc:  # pragma: no cover - import error is defensive
        return [f"Cannot import scripts/docs_to_wiki.py: {exc}"]

    docs_dir = repo_root / "docs"
    wiki_dir = repo_root / "projects" / "wikiforge" / "wiki"
    try:
        bundle, _warnings = docs_to_wiki.build_bundle(repo_root, docs_dir, wiki_dir)
        problems = docs_to_wiki.check_bundle(bundle, wiki_dir, docs_dir)
        # Human-owned notes in the wiki (e.g. notes saved from the UI) are not
        # projections of docs/ and must not fail the sync check. Use the same
        # policy as docs_wiki_drift and docs_to_wiki --check.
        return docs_to_wiki.actionable_problems(problems, wiki_dir)
    except Exception as exc:  # pragma: no cover - defensive
        return [f"Failed to verify generated wiki bundle: {exc}"]


STATE_ROOT_DOCS = {
    "README.md": (
        ".wiki-forge/health/STATUS.md",
        ".wiki-forge/health/metrics/history.jsonl",
        ".wiki-forge/procedures/state/",
        ".wiki-forge/state/",
    ),
    "docs/architettura/ARCHITECTURE.md": (
        ".wiki-forge/health/STATUS.md",
        ".wiki-forge/procedures/state/",
        ".wiki-forge/state/",
    ),
    "docs/processi/KNOWLEDGE_ENGINEERING.md": (
        ".wiki-forge/",
        ".wiki-forge/state/",
    ),
}


def check_state_roots(repo_root: Path) -> list[str]:
    """Keep the unified state root explicit in the active docs."""
    errors: list[str] = []

    for rel, required in STATE_ROOT_DOCS.items():
        path = repo_root / rel
        if not path.exists():
            errors.append(f"State-root documentation '{rel}' is missing.")
            continue
        content = path.read_text(encoding="utf-8")
        for marker in required:
            if marker not in content:
                errors.append(f"State-root documentation '{rel}' no longer documents '{marker}'.")

    return errors


LOCAL_CLAIM_DOCS = (
    "docs/help/inizio.md",
    "docs/guida/GUIDA_OPERATIVA.md",
)
CLOUD_ABSOLUTE_CLAIM_RE = re.compile(
    r"(?:nessun dato inviato in cloud|niente va in cloud)",
    re.IGNORECASE,
)
LOCAL_FIRST_CLAIM_RE = re.compile(r"(?:local-first|installazione locale)", re.IGNORECASE)

def check_local_cloud_claims(repo_root: Path) -> list[str]:
    """Avoid promising cloud behaviour that the configuration does not implement."""
    errors: list[str] = []

    for rel in LOCAL_CLAIM_DOCS:
        path = repo_root / rel
        if not path.exists():
            errors.append(f"Local/cloud claim document '{rel}' is missing.")
            continue
        content = path.read_text(encoding="utf-8")
        if CLOUD_ABSOLUTE_CLAIM_RE.search(content):
            errors.append(f"'{rel}' must not promise that no data ever reaches a configured service.")
        if not LOCAL_FIRST_CLAIM_RE.search(content):
            errors.append(f"'{rel}' must describe the local-first deployment model explicitly.")

    guide = repo_root / "docs" / "guida" / "GUIDA_OPERATIVA.md"
    if guide.exists() and "cloud_backup_webdav" in guide.read_text(encoding="utf-8"):
        content = guide.read_text(encoding="utf-8")
        if not re.search(r"cloud_backup_webdav[\s\S]{0,200}?non[\s\S]{0,80}?(?:collegat|attiv)", content, re.IGNORECASE):
            errors.append("The inert cloud_backup_webdav hook must be documented as not active.")
    elif guide.exists():
        errors.append("docs/guida/GUIDA_OPERATIVA.md must document the inert cloud_backup_webdav hook.")

    return errors


def check_doc_metrics(repo_root: Path) -> list[str]:
    """Verify manifest-derived metric blocks and numeric prose in active docs."""
    try:
        import gen_doc_metrics
    except ImportError as exc:
        return [f"Cannot import scripts/gen_doc_metrics.py: {exc}"]
    try:
        return gen_doc_metrics.check_docs(repo_root)
    except (FileNotFoundError, ValueError, KeyError) as exc:
        return [f"Failed to verify generated doc metrics: {exc}"]


def main():
    import argparse
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    parser = argparse.ArgumentParser(description="Check documentation and skills synchronization")
    parser.add_argument("--json", action="store_true", help="Output result as JSON object on stdout.")
    parser.add_argument(
        "--fix",
        action="store_true",
        help="Refresh stale DOC_BLOCK_REF hashes in docs/help/ before checking.",
    )

    args = parser.parse_args()
    repo_root = Path(__file__).resolve().parent.parent
    commands = parse_skill_commands(repo_root)
    if not commands:
        msg = "ERROR: No commands found in skills/*/SKILL.md frontmatter."
        if args.json:
            import json
            print(json.dumps({"status": "error", "message": msg}))
        else:
            print(msg, file=sys.stderr)
        sys.exit(1)

    all_errors = []

    # Check the single human-readable command catalog. README.md and TUTORIAL.md
    # intentionally link to it instead of duplicating the table.
    catalog = repo_root / "docs" / "riferimenti" / "SLASH_COMMANDS_REFERENCE.md"
    catalog_errors = check_doc_mentions(commands, catalog, "docs/riferimenti/SLASH_COMMANDS_REFERENCE.md")
    all_errors.extend(catalog_errors)

    # Check semantic references from docs/help/ to master blocks.
    semantic_errors = check_semantic_refs(repo_root, fix=args.fix)
    all_errors.extend(semantic_errors)

    # Check version parity
    version_errors = check_version_sync(repo_root)
    all_errors.extend(version_errors)

    # Check in-app help topics (docs/help/*.md)
    help_errors = check_help_topics(repo_root)
    all_errors.extend(help_errors)

    # Check the committed OKF projection of docs/ (self-documentation wiki)
    wiki_errors = check_generated_wiki(repo_root)
    all_errors.extend(wiki_errors)

    # Check that the two state roots stay explicitly distinct in active docs.
    state_root_errors = check_state_roots(repo_root)
    all_errors.extend(state_root_errors)

    # Check that local/cloud claims match the configured (inert) backup hook.
    local_cloud_errors = check_local_cloud_claims(repo_root)
    all_errors.extend(local_cloud_errors)

    metric_errors = check_doc_metrics(repo_root)
    all_errors.extend(metric_errors)

    if args.json:
        import json
        print(json.dumps({
            "status": "error" if all_errors else "success",
            "commands_checked": len(commands),
            "errors": all_errors,
        }))
        sys.exit(1 if all_errors else 0)

    if all_errors:
        print("❌ Doc & Skill Sync Verification Failed:\n", file=sys.stderr)
        for err in all_errors:
            print(f"  - {err}", file=sys.stderr)
        sys.exit(1)
    else:
        print(f"✅ Doc & Skill Sync Verification Passed ({len(commands)} commands checked against skills and the canonical catalog; semantic help refs, CHANGELOG.md and docs/wiki projection in sync).")
        sys.exit(0)

if __name__ == "__main__":
    main()
