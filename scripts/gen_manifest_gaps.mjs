import { readFile, writeFile, mkdir } from 'node:fs/promises';
import * as path from 'node:path';
import { deriveCommandManifest } from './lib/commandManifest.mjs';

const REPO_ROOT = path.resolve(process.cwd());
const OUT = path.join(REPO_ROOT, 'docs', 'riferimenti', 'MANIFEST_GAPS.md');

const main = async () => {
  const manifest = await deriveCommandManifest();
  const gaps = manifest.gaps ?? [];
  const lines = [];
  lines.push('# Manifest Gaps');
  lines.push('');
  lines.push('> Auto-generated by `scripts/gen_manifest_gaps.mjs` from the command manifest. Do not edit by hand.');
  lines.push('');
  lines.push(`Total gaps: **${gaps.length}** (route-without-bus: ${gaps.filter(g => g.kind === 'route-without-bus').length}, slash-without-implementation: ${gaps.filter(g => g.kind === 'slash-without-implementation').length}).`);
  lines.push('');
  lines.push('| # | Kind | Id | Cause | Owner | Action |');
  lines.push('|---:|---|---|---|---|---|');
  gaps.forEach((gap, index) => {
    const cause = gap.detail || 'catalogued without dedicated implementation';
    const owner = gap.kind === 'route-without-bus' ? 'backend' : 'knowledge';
    const action = gap.kind === 'route-without-bus'
      ? 'wire a bus handler or remove the route'
      : 'add a dedicated case in processChatCommand or deprecate the slash command';
    lines.push(`| ${index + 1} | ${gap.kind} | \`${gap.id}\` | ${cause} | ${owner} | ${action} |`);
  });
  lines.push('');
  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, lines.join('\n') + '\n', 'utf-8');
  console.log(`Wrote ${path.relative(REPO_ROOT, OUT)} (${gaps.length} gaps).`);
};

void main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
